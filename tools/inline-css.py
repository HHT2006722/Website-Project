# -*- coding: utf-8 -*-
"""把 css/styles.css 同步进每个页面的 <style>，并保证 <html> 上有 js 类。
Copy css/styles.css into every page's <style> and keep the js class on <html>.

为什么内联：实测 GitHub Pages 的 styles.css 偶发要 9-11 秒才返回，
而它是渲染阻塞资源——卡住时页面就是无样式状态，弱网/微信里看起来
像「打不开」。内联之后首屏不再依赖第二个网络请求。
Why inline: on GitHub Pages the stylesheet occasionally took 9-11 s to
return, and it blocks rendering — while it hangs the page has no styles,
which on a weak connection looks like "the site is down". Inlined, the
first screen no longer waits on a second request.

内联时把注释去掉：注释留在源文件里（中英各一行），页面上不需要，
十二个页面各带一份会白占体积。
Comments are stripped while inlining: they stay in the source file (one
Chinese line, one English line), but shipping them inside twelve pages
would only add weight.

用法：python tools/inline-css.py
每次改完 css/styles.css 都要跑一次（脚本会替换已有的 <style> 内容）。
Usage: python tools/inline-css.py — run it after every CSS change
(it replaces the existing <style> block).
"""
import io, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSS_PATH = os.path.join(ROOT, "css", "styles.css")
PAGES = ["index.html", "works.html", "journal.html", "about.html", "contact.html", "404.html",
         "zh/index.html", "zh/works.html", "zh/journal.html", "zh/about.html",
         "zh/contact.html", "zh/404.html"]

JS_FLAG = "<script>document.documentElement.classList.add('js');</script>\n"
# 页面里的标记也写成中英两行
# The marker inside each page is bilingual too
HEADER = ("    /* 本段由 tools/inline-css.py 从 css/styles.css 生成；改样式请改源文件后重跑 */\n"
          "    /* Generated by tools/inline-css.py from css/styles.css — edit the source and re-run */\n")

LINK_RE = re.compile(r'[ \t]*<link rel="stylesheet" href="css/styles\.css">\n')
# 匹配脚本生成的 style 块（含标记注释），整段替换
# Match the generated style block (marker comment included) and replace it whole
STYLE_RE = re.compile(r'  <style>\n    /\* 本段由 tools/inline-css\.py.*?\n  </style>\n', re.S)


def strip_comments(css):
    """去掉 CSS 注释，并把留下的空行压掉。
    Remove CSS comments and squeeze the blank lines they leave behind."""
    css = re.sub(r"/\*[\s\S]*?\*/", "", css)
    css = re.sub(r"\n{3,}", "\n\n", css)
    return css.strip("\n")


def main():
    with io.open(CSS_PATH, encoding="utf-8") as f:
        css = f.read()
    if "</style" in css:
        raise SystemExit("CSS 里出现了 </style，无法安全内联")

    inlined = strip_comments(css)
    block = "  <style>\n" + HEADER + inlined + "\n  </style>\n"

    for name in PAGES:
        p = os.path.join(ROOT, *name.split("/"))
        with io.open(p, encoding="utf-8") as f:
            s = f.read()

        changed = False

        if LINK_RE.search(s):
            s = LINK_RE.sub(block, s, count=1)
            changed = True
            how = "link → style"
        elif STYLE_RE.search(s):
            s = STYLE_RE.sub(block, s, count=1)
            changed = True
            how = "刷新 style"
        else:
            how = "未找到样式位置"

        if "classList.add('js')" not in s:
            s = s.replace("<head>\n", "<head>\n  " + JS_FLAG, 1)
            changed = True

        if changed:
            with io.open(p, "w", encoding="utf-8", newline="\n") as f:
                f.write(s)
            print(f"OK   {name}: {how}（{len(inlined)} 字符，去掉了注释）")
        else:
            print(f"SKIP {name}: {how}")


if __name__ == "__main__":
    main()
